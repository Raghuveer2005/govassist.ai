async function updateAllSchemes() {
  const schemesDataPath = path.join(__dirname, '../data/schemesData.js');
  const schemes = require('../data/schemesData');

  console.log(`🔍 Updating ${schemes.length} schemes with official application URLs...`);

  // 1. Update schemesData.js in memory
  const updatedSchemes = schemes.map((s, idx) => {
    const id = idx + 1;
    const url = SCHEME_URLS[id] || `https://www.myscheme.gov.in/search?q=${encodeURIComponent(s.scheme_name)}`;
    return {
      ...s,
      application_url: url,
    };
  });

  const fileContent = `/**
 * Comprehensive Dataset of 300 Government Schemes with deterministic eligibility criteria
 * and verified official government application URLs.
 */

const SCHEMES_DATA = ${JSON.stringify(updatedSchemes, null, 2)};

module.exports = SCHEMES_DATA;
`;

  fs.writeFileSync(schemesDataPath, fileContent, 'utf8');
  console.log('✅ Updated backend/data/schemesData.js successfully.');

  // 2. Update MySQL Database
  let connection;
  try {
    connection = await mysql.createConnection({
      host: process.env.DB_HOST || 'localhost',
      port: Number(process.env.DB_PORT) || 3306,
      user: process.env.DB_USER || 'root',
      password: process.env.DB_PASSWORD || 'raghuveer',
      database: process.env.DB_NAME || 'govassist_ai',
    });

    console.log('🔌 Connected to MySQL. Updating database records...');

    // Clear and reset auto-increment to cleanly re-populate all 300 schemes
    await connection.query('DELETE FROM schemes');
    await connection.query('ALTER TABLE schemes AUTO_INCREMENT = 1');

    for (const scheme of updatedSchemes) {
      await connection.query(
        'INSERT INTO schemes (scheme_name, description, category, eligibility_criteria, application_url) VALUES (?, ?, ?, ?, ?)',
        [
          scheme.scheme_name,
          scheme.description,
          scheme.category,
          JSON.stringify(scheme.eligibility_criteria),
          scheme.application_url,
        ]
      );
    }

    const [rows] = await connection.query('SELECT COUNT(*) as total FROM schemes WHERE application_url != ""');
    console.log(`🎉 Successfully updated MySQL! ${rows[0].total} schemes now have active official application URLs.`);
  } catch (err) {
    console.error('⚠️ MySQL update error:', err.message);
  } finally {
    if (connection) await connection.end();
  }
}

updateAllSchemes().catch((err) => {
  console.error('Fatal error:', err);
  process.exit(1);
});
